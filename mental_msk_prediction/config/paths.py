"""
Centralized path configuration for the mental-to-MSK prediction project.

All project modules should import file and directory paths from this file.
"""

from pathlib import Path


# Project roots
# mental_msk_prediction/
PROJECT_DIR = Path(__file__).resolve().parents[1]

# BiostatisticsPracticum_Depression/
REPOSITORY_ROOT = PROJECT_DIR.parent


# Data directories
DATA_DIR = REPOSITORY_ROOT / "data"

RAW_DATA_DIR = DATA_DIR / "raw"
CLEANED_DATA_DIR = DATA_DIR / "cleaned"


# Project output directories
RESULTS_DIR = PROJECT_DIR / "results"

RESULTS_DATA_DIR = RESULTS_DIR / "data"
TABLES_DIR = RESULTS_DIR / "tables"
FIGURES_DIR = RESULTS_DIR / "figures"


# Raw CPCSSN input files
RAW_PATIENT_FILE = RAW_DATA_DIR / "C4MPatient.csv"
RAW_DIAGNOSIS_FILE = RAW_DATA_DIR / "C4MEncounterdiagnosis.csv"
RAW_MEDICATION_FILE = RAW_DATA_DIR / "C4MMedication.csv"


# Cleaned data files
CLEANED_PATIENT_FILE = CLEANED_DATA_DIR / "patient_clean.csv"
CLEANED_DIAGNOSIS_FILE = CLEANED_DATA_DIR / "diagnosis_clean.csv"
CLEANED_MEDICATION_FILE = CLEANED_DATA_DIR / "medication_clean.csv"

# Directory helpers
def create_project_directories() -> None:
    """
    Create directories generated by the analysis pipeline.
    Raw data directories are not populated or modified by this function.
    """
    directories = [
        RAW_DATA_DIR,
        CLEANED_DATA_DIR,
        RESULTS_DATA_DIR,
        TABLES_DIR,
        FIGURES_DIR,
    ]

    for directory in directories:
        directory.mkdir(parents=True, exist_ok=True)


def validate_required_raw_files() -> None:
    """
    Raise an informative error when required CPCSSN files are missing.
    """
    required_files = [
        RAW_PATIENT_FILE,
        RAW_DIAGNOSIS_FILE,
        RAW_MEDICATION_FILE,
    ]

    missing_files = [
        file_path
        for file_path in required_files
        if not file_path.exists()
    ]

    if missing_files:
        missing_text = "\n".join(
            f"  - {file_path}" for file_path in missing_files
        )

        raise FileNotFoundError(
            "Required raw data files were not found:\n"
            f"{missing_text}\n\n"
            "Place the CPCSSN files in data/raw/. "
            "These files must not be committed to GitHub."
        )